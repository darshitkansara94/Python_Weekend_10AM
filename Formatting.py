#     Formatting refers to the way we structure and present our code for better readability and maintainability.
#     To format the text we cn use {} brackets follwed by 'f' sign at the start of the string.

#     Syntax :
#         f"Text {value} is assigned"

#     Example :
name = "Alice"
lastname = "Smith"
print(f"Name is {name} and {lastname}")
