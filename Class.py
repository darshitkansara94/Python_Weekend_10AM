# Class :
#     Class is a collection of metods / function and properties.
#     Properties is nothing but a variable. we can create multiple variable
#         inside class.
#     Also we can create multiple function in the single class.
#     Class name must be start with lower case. 
#     Space is not allowed in class. if we need a space we can use '_' instead of space.
#     Special char and numbers are not allowed in class name.

#     Object :
#       Object is, memory initialization for the class.
#       By using object creation we can access property or methd of the class.
#       We can access property and method of the class by the object name.

#       Syntax :
#            variable_name = class_name()

#     Syntax :
#         class class_name():
