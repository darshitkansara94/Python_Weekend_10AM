# Math :
    # Math module use to calculate value or for the value conversion.
    # To use all the function of math we need to import math module.

    # Example :

import math

# Square root
sqrrt = math.sqrt(25)
print(sqrrt)

square_root = math.sqrt(10)
print(square_root)

# Pi
Pi_value = math.pi
print(Pi_value)

# floor and ceiling
# Ceiling :
    # Ceiling round upe the value but in upwards.

    # Example :

ceil_val = math.ceil(4.86)
print(ceil_val)

# floor :
    # floor use to round up the value but in downwards.

    # Example :
floor_val = math.floor(4.25)
print(floor_val)

# Absolute :
    # Absolute value use to convert negative value into positive value.

    # Example :

absolute_val = math.fabs(-25)
print(absolute_val)

# Factorial :
    # Calculate factorial value.

    # Example :

fact = math.factorial(5)
print(fact)

# Power :
    # Calculate power of the value

    # Example :

power_val = math.pow(2,2) # 2 x 2
print(power_val)